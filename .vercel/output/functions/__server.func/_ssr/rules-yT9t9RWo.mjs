var OWNER_REPO = /^[\w.-]+$/;
function canonicalGithubUrl(raw) {
	try {
		const parsed = new URL(raw.trim());
		if (parsed.protocol !== "https:" && parsed.protocol !== "http:") return null;
		if (parsed.hostname.replace(/^www\./, "").toLowerCase() !== "github.com") return null;
		const parts = parsed.pathname.replace(/\.git$/i, "").split("/").filter(Boolean);
		if (parts.length < 2) return null;
		const [owner, repo] = parts;
		if (!owner || !repo || !OWNER_REPO.test(owner) || !OWNER_REPO.test(repo)) return null;
		return {
			url: `https://github.com/${owner}/${repo}`,
			key: `github.com/${owner.toLowerCase()}/${repo.toLowerCase()}`
		};
	} catch {
		return null;
	}
}
function canonicalHttpUrl(raw) {
	try {
		const parsed = new URL(raw.trim());
		if (parsed.protocol !== "https:" && parsed.protocol !== "http:") return null;
		if (!parsed.hostname) return null;
		return parsed.toString();
	} catch {
		return null;
	}
}
